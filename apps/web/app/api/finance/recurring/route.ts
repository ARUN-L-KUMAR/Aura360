import { NextRequest, NextResponse } from "next/server"
import { getWorkspaceContext } from "@/lib/auth-helpers"
import { db, subscriptions, transactions } from "@/lib/db"
import { eq, and, desc, sql } from "drizzle-orm"
import { processDueRecurringBills } from "@/lib/services/recurring-engine"

// GET /api/finance/recurring - Fetch recurring bills status and auto-logged entries
export async function GET() {
  try {
    const context = await getWorkspaceContext()

    // 1. Active recurring bills / subscriptions
    const activeRecurring = await db
      .select()
      .from(subscriptions)
      .where(
        and(
          eq(subscriptions.workspaceId, context.workspaceId),
          eq(subscriptions.userId, context.userId),
          eq(subscriptions.status, "active")
        )
      )
      .orderBy(subscriptions.nextBillingDate)

    // 2. Ledger entries generated by recurring engine
    const recurringTransactions = await db
      .select()
      .from(transactions)
      .where(
        and(
          eq(transactions.workspaceId, context.workspaceId),
          eq(transactions.userId, context.userId),
          sql`metadata->>'isRecurring' = 'true'`
        )
      )
      .orderBy(desc(transactions.date))
      .limit(50)

    return NextResponse.json({
      success: true,
      activeRecurring,
      recentRecurringTransactions: recurringTransactions,
      totalRecurringCount: activeRecurring.length,
    })
  } catch (error: any) {
    console.error("[GET /api/finance/recurring error]:", error)
    return NextResponse.json(
      { success: false, error: error.message || "Failed to fetch recurring bills" },
      { status: 500 }
    )
  }
}

// POST /api/finance/recurring - Process due recurring transactions immediately
export async function POST(request: NextRequest) {
  try {
    const context = await getWorkspaceContext()
    const body = await request.json().catch(() => ({}))
    const targetDate = body.targetDate || new Date().toISOString().split("T")[0]
    const dryRun = Boolean(body.dryRun)

    const result = await processDueRecurringBills(context, targetDate, { dryRun })

    return NextResponse.json({
      success: true,
      message: `Processed ${result.processedCount} recurring transactions`,
      ...result,
    })
  } catch (error: any) {
    console.error("[POST /api/finance/recurring error]:", error)
    return NextResponse.json(
      { success: false, error: error.message || "Failed to process recurring transactions" },
      { status: 500 }
    )
  }
}

